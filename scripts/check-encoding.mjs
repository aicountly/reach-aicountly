export const BOM = '\uFEFF';

/** Lockfiles and vendored code are tool-generated; their bytes are not ours to police. */
const SKIP = [/^server-php\/composer\.lock$/, /^web\/package-lock\.json$/, /^server-php\/vendor\//];

function trackedFiles(root) {
  return execFileSync('git', ['ls-files', '-z'], { cwd: root, maxBuffer: 64 * 1024 * 1024 })
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .filter((f) => !SKIP.some((re) => re.test(f)));
}

/** @returns {{file: string, line: number, found: string, expected: string, name: string}[]} */
export function scanRepo(root = REPO_ROOT) {
  const problems = [];

  for (const file of trackedFiles(root)) {
    let text;
    try {
      const raw = readFileSync(path.join(root, file));
      if (raw.includes(0)) continue; // binary
      text = raw.toString('utf8');
    } catch {
      continue; // deleted or unreadable in this checkout
    }

    if (text.startsWith(BOM)) {
      problems.push({ file, line: 1, found: 'UTF-8 BOM', expected: '(no BOM)', name: 'byte order mark' });
    }

    if (!MOJIBAKE.some(([bad]) => text.includes(bad))) continue;

    text.split('\n').forEach((lineText, i) => {
      for (const [bad, good, name] of MOJIBAKE) {
        if (lineText.includes(bad)) {
          problems.push({ file, line: i + 1, found: bad, expected: good, name });
        }
      }
    });
  }

  return problems;
}

function main(argv) {
  // An explicit root keeps the guard testable against a throwaway fixture repo.
  const problems = scanRepo(argv[2] ? path.resolve(argv[2]) : REPO_ROOT);
  if (problems.length === 0) {
    console.log('Encoding guard: clean - no mojibake or BOM in tracked files.');
    return 0;
  }
  console.error(`Encoding guard: ${problems.length} problem(s) found.\n`);
  for (const p of problems) {
    console.error(
      `  ${p.file}:${p.line}  ${JSON.stringify(p.found)} should be ${JSON.stringify(p.expected)} (${p.name})`,
    );
  }
  console.error('\nSave the file as UTF-8 without a BOM. Do not round-trip source files');
  console.error('through PowerShell Get-Content/Set-Content or a CP437/CP1252 console.');
  return 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv));
}
